#!/usr/bin/env python3
"""Figures for the E02 writeup, drawn from data/e02/summary.json.

Usage: figures.py [SUMMARY_JSON] [--out DIR]
"""

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import matplotlib.ticker  # noqa: E402,F401

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

# Reference palette, light mode; slots 1-3 validate all-pairs (see the dataviz notes).
INK, INK_2, MUTED, GRID = "#0b0b0b", "#52514e", "#8a8984", "#e6e5e0"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a"]

plt.rcParams.update({
    "font.family": "DejaVu Sans", "font.size": 9, "text.color": INK,
    "axes.edgecolor": MUTED, "axes.labelcolor": INK_2, "axes.linewidth": 0.8,
    "axes.spines.top": False, "axes.spines.right": False,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
    "xtick.color": INK_2, "ytick.color": INK_2, "svg.fonttype": "path",
})


def line(ax, xs, ys, colour, label, dy=0, fmt="{:,}"):
    ax.plot(xs, ys, color=colour, linewidth=2, marker="o", markersize=5,
            markeredgecolor="white", markeredgewidth=1, label=label, zorder=3)
    ax.annotate(fmt.format(ys[-1]), (xs[-1], ys[-1]), xytext=(8, dy),
                textcoords="offset points", va="center", color=INK, fontsize=8.5)


def counts(summary, out):
    rows = summary["rows"]
    ns = [int(n) for n in summary["sizes"]]
    fig, ax = plt.subplots(figsize=(6.2, 3.4))
    series = [
        ("generated", "generated by tricensus -M", lambda r: r["generated"]),
        ("census", "minimal (in the census)", lambda r: r["census"]),
        ("hard", "non-minimal, one simplify() call stuck", lambda r: sum(
            r[k] for k in ("exhaustive:1", "exhaustive:2", "exhaustive:3"))),
    ]
    for colour, (_, label, f) in zip(SERIES, series):
        pts = [(n, f(rows[str(n)])) for n in ns if f(rows[str(n)]) > 0]
        line(ax, [p[0] for p in pts], [p[1] for p in pts], colour, label)
    ax.set_yscale("log")
    ax.yaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:,.0f}"))
    ax.set_xticks(ns)
    ax.set_xlim(ns[0] - 0.3, ns[-1] + 1.3)
    ax.set_xlabel("n (tetrahedra)")
    ax.set_ylabel("closed orientable triangulations")
    ax.legend(loc="upper left", frameon=False, fontsize=8.5)
    fig.tight_layout()
    fig.savefig(out / "counts.svg")
    plt.close(fig)


def gen_time(summary, out):
    rows = summary["rows"]
    ns = [int(n) for n in summary["sizes"] if rows[str(n)]["gen_secs"] >= 0.05]
    ys = [rows[str(n)]["gen_secs"] for n in ns]
    fig, ax = plt.subplots(figsize=(6.2, 3.0))
    ax.plot(ns, ys, color=SERIES[0], linewidth=2, marker="o", markersize=5,
            markeredgecolor="white", markeredgewidth=1, zorder=3)
    for n, y in zip(ns, ys):
        label = (f"{y / 3600:.1f} h" if y >= 3600 else f"{y / 60:.0f} min" if y >= 120
                 else f"{y:.1f} s" if y < 10 else f"{y:.0f} s")
        if rows[str(n)].get("chunks"):
            label += "*"
        ax.annotate(label, (n, y), xytext=(0, 7), textcoords="offset points",
                    ha="center", color=INK_2, fontsize=8)
    ax.set_yscale("log")
    ticks = [(0.1, "0.1 s"), (1, "1 s"), (10, "10 s"), (60, "1 min"), (600, "10 min"),
             (3600, "1 h"), (4 * 3600, "4 h")]
    ticks = [t for t in ticks if min(ys) / 3 <= t[0] <= max(ys) * 1.2]
    ax.yaxis.set_major_locator(matplotlib.ticker.FixedLocator([t[0] for t in ticks]))
    ax.yaxis.set_minor_locator(matplotlib.ticker.NullLocator())
    ax.yaxis.set_major_formatter(matplotlib.ticker.FixedFormatter([t[1] for t in ticks]))
    ax.set_xticks(ns)
    ax.set_xlabel("n (tetrahedra)")
    ax.set_ylabel(f"tricensus time\n({summary['run']['params']['workers']} threads)")
    ax.margins(y=0.3)
    fig.tight_layout()
    fig.savefig(out / "generation_time.svg")
    plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("summary", nargs="?", type=Path, default=ROOT / "data/e02/summary.json")
    ap.add_argument("--out", type=Path, default=HERE / "figures")
    args = ap.parse_args()
    summary = json.loads(args.summary.read_text())
    args.out.mkdir(parents=True, exist_ok=True)
    counts(summary, args.out)
    gen_time(summary, args.out)
    print(f"wrote {args.out}/counts.svg, generation_time.svg")


if __name__ == "__main__":
    main()
